import { BOARD, DISTRICTS } from "../game/board";
import { CARDS } from "../game/cards";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);

/** SQL that (re)seeds board_tiles and card_definitions. Idempotent. */
export function buildSeedSql(): string {
  const lines: string[] = [
    "-- ===========================================================================",
    "-- Empire City — board & card seed (GENERATED by `npm run db:generate-seed`,",
    "-- source of truth: src/lib/game/board.ts and src/lib/game/cards.ts)",
    "-- ===========================================================================",
    "",
  ];
  lines.push(
    "insert into public.board_tiles (idx, kind, name, district, district_name, district_color, price, rent, house_cost, mortgage, multipliers, tax_amount) values",
  );
  lines.push(
    BOARD.map((t) => {
      const d = t.district ? DISTRICTS[t.district] : null;
      return `  (${t.index}, ${q(t.kind)}, ${q(t.name)}, ${q(t.district ?? null)}, ${q(d?.name)}, ${q(d?.color)}, ${n(t.price)}, ${j(t.rent)}, ${n(t.houseCost)}, ${n(t.mortgage)}, ${j(t.multipliers)}, ${n(t.taxAmount)})`;
    }).join(",\n"),
  );
  lines.push(
    "on conflict (idx) do update set kind = excluded.kind, name = excluded.name, district = excluded.district, district_name = excluded.district_name, district_color = excluded.district_color, price = excluded.price, rent = excluded.rent, house_cost = excluded.house_cost, mortgage = excluded.mortgage, multipliers = excluded.multipliers, tax_amount = excluded.tax_amount;",
  );
  lines.push("");
  lines.push("insert into public.card_definitions (id, deck, title, body, effect) values");
  lines.push(CARDS.map((c) => `  (${q(c.id)}, ${q(c.deck)}, ${q(c.title)}, ${q(c.text)}, ${j(c.effect)})`).join(",\n"));
  lines.push(
    "on conflict (id) do update set deck = excluded.deck, title = excluded.title, body = excluded.body, effect = excluded.effect;",
  );
  lines.push("");
  return lines.join("\n");
}
