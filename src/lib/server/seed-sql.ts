import { BOARDS, BOARD_IDS, DISTRICTS } from "../game/board";
import { CARDS } from "../game/cards";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);

export const SEED_MIGRATION_FILE = "20261122000006_seed_boards.sql";

/** SQL that (re)seeds board_tiles for every board variant and card_definitions. Idempotent. */
export function buildSeedSql(): string {
  const lines: string[] = [
    "-- ===========================================================================",
    "-- Empire City — boards & cards seed (GENERATED by `npm run db:generate-seed`,",
    "-- source of truth: src/lib/game/board.ts and src/lib/game/cards.ts).",
    "-- Boards: classic (40), standard (48), maxi (64). Requires the board_variants migration.",
    "-- ===========================================================================",
    "",
    "insert into public.board_tiles (board, idx, kind, name, district, district_name, district_color, price, rent, house_cost, mortgage, multipliers, tax_amount) values",
  ];
  const rows: string[] = [];
  for (const id of BOARD_IDS) {
    for (const t of BOARDS[id].tiles) {
      const d = t.district ? DISTRICTS[t.district] : null;
      rows.push(
        `  (${q(id)}, ${t.index}, ${q(t.kind)}, ${q(t.name)}, ${q(t.district ?? null)}, ${q(d?.name)}, ${q(d?.color)}, ${n(t.price)}, ${j(t.rent)}, ${n(t.houseCost)}, ${n(t.mortgage)}, ${j(t.multipliers)}, ${n(t.taxAmount)})`,
      );
    }
  }
  lines.push(rows.join(",\n"));
  lines.push(
    "on conflict (board, idx) do update set kind = excluded.kind, name = excluded.name, district = excluded.district, district_name = excluded.district_name, district_color = excluded.district_color, price = excluded.price, rent = excluded.rent, house_cost = excluded.house_cost, mortgage = excluded.mortgage, multipliers = excluded.multipliers, tax_amount = excluded.tax_amount;",
  );
  lines.push("");
  lines.push("insert into public.card_definitions (id, deck, title, body, effect) values");
  lines.push(CARDS.map((c) => `  (${q(c.id)}, ${q(c.deck)}, ${q(c.title)}, ${q(c.text)}, ${j(c.effect)})`).join(",\n"));
  lines.push(
    "on conflict (id) do update set deck = excluded.deck, title = excluded.title, body = excluded.body, effect = excluded.effect;",
  );
  lines.push("");
  return lines.join("\n");
}
