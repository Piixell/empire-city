// Concatenates every migration into supabase/setup.sql, ready to paste in the
// Supabase SQL Editor (alternative to `supabase db push`).
//   npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.resolve(import.meta.dirname, "../supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `-- >>> ${f}\n${readFileSync(path.join(dir, f), "utf8")}`).join("\n\n");
const out = path.resolve(import.meta.dirname, "../supabase/setup.sql");
writeFileSync(out, `-- Empire City — full database setup (GENERATED by npm run db:bundle)\n-- Paste into Supabase → SQL Editor → Run.\n\n${body}`, "utf8");
console.log(`Bundled ${files.length} migrations into ${out}`);
